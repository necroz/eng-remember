"""Declarative base and shared column mixins."""

from __future__ import annotations

from datetime import UTC, datetime

from sqlalchemy import DateTime, MetaData, TypeDecorator, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from eng_remember.utils.time import ensure_utc


class UtcDateTime(TypeDecorator[datetime]):
    """A timestamp that is always read back as an aware UTC datetime.

    PostgreSQL's ``timestamptz`` keeps the offset; SQLite silently drops it and
    returns naive values. Normalising in the column type means no caller has to
    know which backend it is talking to — and mixing the two flavours is a
    ``TypeError`` that would otherwise surface only in production.
    """

    impl = DateTime(timezone=True)
    cache_ok = True

    def process_bind_param(self, value: datetime | None, dialect: object) -> datetime | None:
        del dialect
        moment = ensure_utc(value)
        return moment.astimezone(UTC) if moment is not None else None

    def process_result_value(self, value: datetime | None, dialect: object) -> datetime | None:
        del dialect
        return ensure_utc(value)


# Deterministic constraint names. Without this, autogenerated migrations get
# database-assigned names and any later drop/alter becomes guesswork.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class TimestampMixin:
    """``created_at`` / ``updated_at`` maintained by the database itself."""

    created_at: Mapped[datetime] = mapped_column(
        UtcDateTime,
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        UtcDateTime,
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
